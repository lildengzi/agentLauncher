const dicts: Record<Locale, Dict> = { zh, en };

export function setLocale(l: Locale): void {
  config.ui.locale = l; // ref + cache update via the watcher above; persisted by launcherConfig
}

export function useI18n() {
  const t = (key: string): string => dicts[locale.value][key] ?? key;
  return { t, locale: readonly(locale), setLocale, isZh: computed(() => locale.value === "zh") };
}
